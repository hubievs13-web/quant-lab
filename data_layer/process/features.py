"""Feature engineering for the Market Research Data Layer (Phase 3).

Reads `processed/bars_joined/binance/<SYMBOL>/<TF>.parquet` plus the
raw daily OI metrics parquets for crowding columns, and emits
`processed/features/binance/<SYMBOL>/<TF>.parquet`.

Anti-lookahead policy: every feature for bar `i` is a function of
closed bar `i` and bars `< i`. No future bars are referenced. Pandas
`.rolling`, `.ewm`, `.shift(positive)`, and `.pct_change` with
non-negative offsets are the only time-series ops used.

Definitions and window parameters live in
`data_layer/config/features.yaml`. Feature catalog (human-readable)
is regenerated by `data_layer/scripts/refresh_summaries.py`.
"""
from __future__ import annotations

import datetime as dt
import glob
import math
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd
import pyarrow as pa

from data_layer.ingest.common import write_parquet_atomic

# bars per day per timeframe
BARS_PER_DAY = {"5m": 288, "1h": 24}
BARS_PER_HOUR = {"5m": 12, "1h": 1}
TF_MIN = {"5m": 5, "1h": 60}
FUNDING_INTERVAL_MIN = 480  # 8h default for Binance perp


@dataclass(frozen=True)
class FeatureSpec:
    name: str
    description: str
    inputs: tuple[str, ...]
    window: str  # e.g. "1 bar", "24 bars", "30 days"


